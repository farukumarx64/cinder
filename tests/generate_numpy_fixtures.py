#!/usr/bin/env python3
"""Generate float32 NumPy references; never invoke or import Cinder."""

import argparse
from pathlib import Path

import numpy as np


SEED = 20261016
ROOT = Path(__file__).resolve().parent


def f32(values):
    return np.asarray(values, dtype=np.float32)


def softmax(values):
    shifted = np.subtract(values, np.max(values), dtype=np.float32)
    exponentials = np.exp(shifted, dtype=np.float32)
    total = np.sum(exponentials, dtype=np.float32)
    return np.divide(exponentials, total, dtype=np.float32)


def require_array(values, shape):
    if values.dtype != np.float32 or values.shape != shape:
        raise ValueError(f"Expected float32 {shape}, got {values.dtype} {values.shape}")
    if not np.all(np.isfinite(values)):
        raise ValueError("Reference inputs and outputs must be finite")


def dense_cases():
    cases = [
        ("non_square", [[1, -2, 3], [4, 0, -1]], [2, -1, 0.5], [0.5, -9.5]),
        ("decimals", [[0.1, -0.2], [0.3, 0.7], [-1.1, 0.9]],
         [0.6, -0.4], [0.01, -0.02, 0.03]),
        ("identity", np.eye(4, dtype=np.float32), [-3, 0, 0.25, 2], [1, 0, -1, 0.5]),
        ("zero_input", [[1, 2, 3, 4], [-1, -2, -3, -4], [0, 2, 0, -2]],
         [0, 0, 0, 0], [-2, 0, 3]),
        ("zero_weights", np.zeros((2, 3), dtype=np.float32), [2, -4, 8], [0.5, -0.5]),
        ("single_row", [[1, -2, 0.5, 3, -1]], [0.5, 1, -4, 2, 0], [-0.25]),
        ("single_column", [[-2], [0], [0.5], [3]], [-1.5], [0, -1, 0.75, 2]),
        ("scalar", [[-0.75]], [2], [0.25]),
    ]
    # Explicit generator and seed. Small integer draws scaled by powers of two
    # give exactly representable float32 inputs, independent of decimal parsing.
    rng = np.random.Generator(np.random.PCG64(SEED))
    for rows, cols in [(3, 7), (7, 11), (11, 17)]:
        weights = rng.integers(-16, 17, size=(rows, cols), dtype=np.int32)
        inputs = rng.integers(-8, 9, size=cols, dtype=np.int32)
        bias = rng.integers(-8, 9, size=rows, dtype=np.int32)
        cases.append((f"seeded_{rows}x{cols}", f32(weights) / np.float32(8),
                      f32(inputs) / np.float32(4), f32(bias) / np.float32(8)))
    return cases


def activation_cases():
    return [
        ("singleton", [-3.5]),
        ("zeros", [0, 0, 0, 0]),
        ("signed_zeros", [-0.0, 0.0]),
        ("mixed", [-3.25, 0, 0.125, 2.5, -0.75]),
        ("all_negative", [-7, -3, -1]),
        ("all_positive", [1, 2, 3]),
        ("large_positive", [1001, 1002, 1003]),
        ("large_negative", [-999, -998, -997]),
        ("tied_maxima", [1000, 999, 1000, 998]),
        ("equal_extremes", [np.finfo(np.float32).max] * 3),
        ("underflow", [0, -90, -100, -104]),
        ("spread", np.linspace(-20, 20, 33, dtype=np.float32)),
    ]


def emit_array(lines, name, values):
    # A float32 converts exactly to a Python float. C11 hexadecimal literals
    # preserve its bits, including subnormals, without decimal-rounding loss.
    literals = [float(value).hex() + "f" for value in values.ravel(order="C")]
    lines.append(f"static const float {name}[] = {{")
    for start in range(0, len(literals), 4):
        lines.append("    " + ", ".join(literals[start:start + 4]) + ",")
    lines.append("};\n")


def generate():
    lines = [
        "/* Generated by tests/generate_numpy_fixtures.py; do not edit by hand.",
        f" * NumPy {np.__version__}; PCG64 seed {SEED}; all reference arithmetic float32.",
        " * Regenerate explicitly when changing fixtures; see docs/NUMPY_TESTS.md.",
        " */",
        "#ifndef CINDER_NUMPY_FIXTURES_H",
        "#define CINDER_NUMPY_FIXTURES_H\n",
        "#include <stddef.h>\n",
        "typedef struct { const float *data; size_t count; } numpy_vector_t;",
        "typedef struct {",
        "    const char *name;",
        "    size_t rows, cols;",
        "    numpy_vector_t weights, input, bias, matvec, biased, relu, softmax, relu_softmax;",
        "} numpy_dense_fixture_t;",
        "typedef struct {",
        "    const char *name;",
        "    numpy_vector_t input, relu, softmax;",
        "} numpy_activation_fixture_t;\n",
        "#define NUMPY_VECTOR(array) {array, sizeof(array) / sizeof((array)[0])}\n",
    ]
    dense_records = []
    for name, weights, inputs, bias in dense_cases():
        weights, inputs, bias = f32(weights), f32(inputs), f32(bias)
        rows, cols = weights.shape
        require_array(weights, (rows, cols))
        require_array(inputs, (cols,))
        require_array(bias, (rows,))
        product = np.matmul(weights, inputs, dtype=np.float32)
        biased = np.add(product, bias, dtype=np.float32)
        relu = np.maximum(biased, np.float32(0))
        arrays = dict(weights=weights, input=inputs, bias=bias, matvec=product,
                      biased=biased, relu=relu, softmax=softmax(biased),
                      relu_softmax=softmax(relu))
        for stage, values in arrays.items():
            shape = (rows, cols) if stage == "weights" else (cols,) if stage == "input" else (rows,)
            require_array(values, shape)
            emit_array(lines, f"{name}_{stage}", values)
        fields = ", ".join(f"NUMPY_VECTOR({name}_{stage})" for stage in arrays)
        dense_records.append(f'    {{"{name}", {rows}, {cols}, {fields}}},')
    lines.extend(["static const numpy_dense_fixture_t numpy_dense_fixtures[] = {",
                  *dense_records, "};\n"])

    activation_records = []
    for name, inputs in activation_cases():
        inputs = f32(inputs)
        require_array(inputs, (inputs.size,))
        arrays = dict(input=inputs, relu=np.maximum(inputs, np.float32(0)),
                      softmax=softmax(inputs))
        for stage, values in arrays.items():
            require_array(values, inputs.shape)
            emit_array(lines, f"activation_{name}_{stage}", values)
        fields = ", ".join(f"NUMPY_VECTOR(activation_{name}_{stage})" for stage in arrays)
        activation_records.append(f'    {{"{name}", {fields}}},')
    lines.extend(["static const numpy_activation_fixture_t numpy_activation_fixtures[] = {",
                  *activation_records, "};\n", "#undef NUMPY_VECTOR",
                  "#endif /* CINDER_NUMPY_FIXTURES_H */", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "fixtures" / "numpy_fixtures.h")
    args = parser.parse_args()
    # Underflow to a finite zero is allowed by Cinder's math contract.
    with np.errstate(over="raise", invalid="raise", divide="raise", under="ignore"):
        content = generate()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(f"Generated {args.output} with NumPy {np.__version__} (seed {SEED}).")


if __name__ == "__main__":
    main()
