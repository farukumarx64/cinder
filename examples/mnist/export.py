"""Export the saved MNIST checkpoint as Dense -> ReLU -> Dense -> Softmax."""

import argparse
from pathlib import Path
import pickle
import sys
import tempfile

import torch
from torch import nn

# Support both direct execution from any directory and package imports.
ROOT = Path(__file__).resolve().parents[2]
if __package__ in (None, ""):
    sys.path.insert(0, str(ROOT))

from examples.mnist.train import build_model
from tools.export_model import export_model


EXAMPLE = Path(__file__).resolve().parent


def load_inference_model(checkpoint_path: Path) -> nn.Sequential:
    """Restore exact float32 parameters and append a feature-axis Softmax.

    load_state_dict can silently cast tensors, so reject incompatible storage,
    shapes, and dtypes before restoring. Metadata is not used to construct code
    or change the fixed architecture. The checkpoint file is only read.
    """
    checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    if not isinstance(checkpoint, dict) or not isinstance(checkpoint.get("model_state_dict"), dict):
        raise ValueError("checkpoint: expected a dictionary containing model_state_dict")
    state = checkpoint["model_state_dict"]
    model = build_model()
    expected = model.state_dict()
    if state.keys() != expected.keys():
        raise ValueError("checkpoint: expected exactly hidden.weight, hidden.bias, logits.weight, logits.bias")
    for name, tensor in state.items():
        if (type(tensor) is not torch.Tensor or tensor.is_nested or
                tensor.layout != torch.strided or tensor.device.type != "cpu" or
                tensor.dtype != torch.float32 or tensor.shape != expected[name].shape):
            raise ValueError(f"checkpoint {name}: expected a CPU float32 tensor with shape {tuple(expected[name].shape)}")
        if not bool(torch.isfinite(tensor).all()):
            raise ValueError(f"checkpoint {name}: every parameter must be finite")
    model.load_state_dict(state, strict=True)
    model.add_module("probabilities", nn.Softmax(dim=-1))
    model.eval()
    return model


def export_checkpoint(checkpoint: Path, output: Path, *, check: bool = False) -> None:
    """Export using the existing atomic writer, or compare without publishing.

    The output parent must exist. Export may replace an existing output; the
    selected checkpoint itself must never be used as the output path.
    """
    if checkpoint.resolve() == output.resolve():
        raise ValueError("output must differ from the checkpoint path")
    model = load_inference_model(checkpoint)
    if check:
        with tempfile.TemporaryDirectory(prefix="cinder-mnist-export-") as temporary:
            regenerated = Path(temporary) / "mnist.cnd"
            export_model(model, regenerated, input_size=784)
            if regenerated.read_bytes() != output.read_bytes():
                raise ValueError(f"export mismatch: {output} differs from the checkpoint export")
    else:
        export_model(model, output, input_size=784)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", type=Path, default=EXAMPLE / "reference/checkpoint.pt")
    parser.add_argument("--output", type=Path, default=EXAMPLE / "mnist.cnd")
    parser.add_argument("--check", action="store_true",
                        help="compare regenerated bytes with output without modifying it")
    args = parser.parse_args(argv)
    try:
        export_checkpoint(args.checkpoint, args.output, check=args.check)
    except (OSError, ValueError, RuntimeError, EOFError, pickle.UnpicklingError) as error:
        print(f"MNIST export failed: {error}", file=sys.stderr)
        return 1
    print(f"{'Verified identical export:' if args.check else 'Exported:'} {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
